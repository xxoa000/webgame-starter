export function zoneFor(name: string, index = 0) {
  /* 맵 이름을 좌표에 연결하며 추가 맵은 순서에 따른 기본 좌표를 사용한다. */
  return (
    MAP_ZONES.find((zone) => zone.name === name) ??
    MAP_ZONES[index % MAP_ZONES.length]
  );
}
